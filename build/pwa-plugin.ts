import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import type { Plugin } from "vite";

/**
 * Writes dist/sw.js after the build: a service worker that precaches every
 * emitted file (lesson and Mermaid chunks, domain pages, icons, manifest) under
 * a cache named after a hash of their contents, so any content change ships as
 * an update. All URLs are relative to sw.js, so it works under any subpath.
 */
export default function pwa(): Plugin {
  return {
    name: "study-assistant-pwa",
    apply: "build",
    writeBundle({ dir }) {
      if (!dir) return;
      const files = readdirSync(dir, { recursive: true, withFileTypes: true })
        .filter(
          (e) => e.isFile() && !e.name.startsWith(".") && e.name !== "sw.js",
        )
        .map((e) =>
          relative(dir, join(e.parentPath, e.name)).split(sep).join("/"),
        )
        .sort();
      // Pages are usually opened by their directory URL: "./" and "caching/".
      const pages = files
        .filter((f) => /(^|\/)index\.html$/.test(f))
        .map((f) => "./" + f.replace(/index\.html$/, ""));
      const urls = [...pages, ...files.map((f) => "./" + f)];
      // The version covers every file and the worker code itself.
      const hash = createHash("sha256").update(worker("", urls));
      for (const f of files) hash.update(f).update(readFileSync(join(dir, f)));
      writeFileSync(
        join(dir, "sw.js"),
        worker(hash.digest("hex").slice(0, 16), urls),
      );
    },
  };
}

const worker = (
  version: string,
  urls: string[],
) => `// Generated by build/pwa-plugin.ts.
const PREFIX = "study-assistant:" + self.registration.scope + ":";
const CACHE = PREFIX + ${JSON.stringify(version)};
const URLS = ${JSON.stringify(urls)};

self.addEventListener("install", (e) => {
  e.waitUntil(
    caches
      .open(CACHE)
      .then((c) => c.addAll(URLS.map((u) => new Request(u, { cache: "reload" })))),
  );
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((k) => k.startsWith(PREFIX) && k !== CACHE)
            .map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("message", (e) => {
  if (e.data === "skip-waiting") self.skipWaiting();
});

// Cache first: everything the app needs is precached; anything else goes to the network.
// ignoreVary: hosts may send "Vary: Origin" and module scripts carry an Origin header.
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  e.respondWith(
    caches
      .open(CACHE)
      .then((c) => c.match(e.request, { ignoreSearch: true, ignoreVary: true }))
      .then((r) => r || fetch(e.request)),
  );
});
`;
